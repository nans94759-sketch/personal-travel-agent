MODE_LABEL = {
    "en": {"train": "Train", "flight": "Flight"},
    "zh": {"train": "高铁", "flight": "航班"},
}


def normalise(lang: str) -> str:
    return lang if lang in STRINGS else DEFAULT_LANG


def t(lang: str, key: str, **kwargs: Any) -> str:
    table = STRINGS[normalise(lang)]
    template = table.get(key) or STRINGS[DEFAULT_LANG].get(key, key)
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def mode_label(lang: str, mode: str) -> str:
    return MODE_LABEL[normalise(lang)].get(mode, mode)


def ui_strings(lang: str) -> Dict[str, str]:
    return dict(STRINGS[normalise(lang)])
